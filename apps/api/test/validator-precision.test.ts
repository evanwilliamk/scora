// Every check is linear, so a long input costs milliseconds. Best of three on
// a generous bound, since test machines can be heavily loaded.
test('adversarial long inputs stay fast', () => {
  const inputs: Record<string, string> = {
    'whitespace run': `${' '.repeat(100_000)}x`,
    'line breaks': '\n '.repeat(50_000),
    'repeated you': 'you '.repeat(25_000),
    'repeated run': 'run '.repeat(25_000),
    'repeated rest': 'rest '.repeat(20_000),
    'repeated tend to': 'tend to '.repeat(12_500),
    'repeated you ran': `${'you ran '.repeat(12_500)}instead`,
    'one long word': 'a'.repeat(100_000),
    'repeated dots': '.'.repeat(100_000),
    'dots and spaces': '. '.repeat(50_000),
    'repeated commas': ', '.repeat(50_000),
    'repeated question marks': '?'.repeat(100_000),
    'repeated dashes': '- '.repeat(50_000),
    'repeated percents': '8% '.repeat(33_000),
    'repeated numbers': '1 '.repeat(50_000),
    'sport list': 'run 1, '.repeat(14_000),
    'repeated sentences': 'Sleep held. '.repeat(8_500),
  };
  for (const [name, text] of Object.entries(inputs)) {
    let best = Infinity;
    for (let i = 0; i < 3; i++) {
      const at = performance.now();
      validateVoice(text, PLAN);
      best = Math.min(best, performance.now() - at);
    }
    assert.ok(best < 1000, `${name}: ${best.toFixed(0)} ms`);
  }
});
